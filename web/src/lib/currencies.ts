export interface CurrencyOption {
  code: string;
  name: string;
  flag: string;
}

/** Regional-indicator pair, e.g. "US" → 🇺🇸. */
export const flagOf = (country: string | null | undefined): string =>
  country ? String.fromCodePoint(...[...country].map((c) => 0x1f1e6 + c.charCodeAt(0) - 65)) : "🌐";

let options: CurrencyOption[] | null = null;

/** All currencies, sorted by name. */
export function currencyOptions(): CurrencyOption[] {
  if (!options) {
    options = CURRENCIES.map(([code, name, country]) => ({ code, name, flag: flagOf(country) }))
      .sort((a, b) => a.name.localeCompare(b.name));
  }
  return options;
}
